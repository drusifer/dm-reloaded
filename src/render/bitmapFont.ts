export function drawBitmapText(
  fb: Framebuffer,
  text: string,
  x: number,
  y: number,
  color: RgbColor,
  systemFont?: Uint8Array | null,
  maxChars?: number
): void {
  const limit = maxChars !== undefined ? Math.min(text.length, maxChars) : text.length;
  let cursorX = x | 0;
  const baseY = y | 0;

  for (let i = 0; i < limit; i += 1) {
    const rawChar = text[i] ?? ' ';
    const upper = rawChar.toUpperCase();
    const code = upper.charCodeAt(0);

    if (systemFont && systemFont.length === 768 && code >= 32 && code <= 95) {
      for (let row = 0; row < 6; row += 1) {
        const bits = systemFont[row * 128 + code] ?? 0;
        for (let col = 0; col < 6; col += 1) {
          if (((bits >> (5 - col)) & 1) !== 0) {
            fb.setPixel(cursorX + col, baseY + row, color);
          }
        }
      }
      cursorX += 6;
      continue;
    }

    const glyph = FALLBACK_GLYPHS[upper] ?? FALLBACK_GLYPHS['?']!;
    for (let row = 0; row < glyph.length; row += 1) {
      const bits = glyph[row] ?? 0;
      for (let col = 0; col < 5; col += 1) {
        if (((bits >> (4 - col)) & 1) !== 0) {
          fb.setPixel(cursorX + col, baseY + row, color);
        }
      }
    }
    cursorX += 6;
  }
}
